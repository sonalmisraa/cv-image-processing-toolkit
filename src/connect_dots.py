def connect_dots(output_path="results/connected_dots.png"):
    W, H = 1066, 1084
    output = Image.new("1", (W, H), 0)
    draw = ImageDraw.Draw(output)
    ordered = [POINTS[i] for i in range(1, 62)]
    draw.line(ordered, fill=1, width=3)
    for x, y in ordered:
        r = 4
        draw.ellipse((x-r, y-r, x+r, y+r), fill=1)
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    output.convert("L").save(output_path)
    return output_path


